"""Clean and stratify the primary bilingual message dataset."""

from __future__ import annotations

import random
from pathlib import Path

import pandas as pd


EXPECTED_LABELS = {"smish", "normal", "promo"}
SPLIT_RATIOS = {"train": 0.70, "validation": 0.15, "test": 0.15}
RANDOM_SEED = 42


def message_key(message: str) -> str:
    """Build a duplicate-check key without changing the saved message text."""
    return " ".join(message.split()).casefold()


def allocate_counts(row_count: int) -> dict[str, int]:
    """Allocate rows to splits using largest remainders for the requested ratios."""
    exact_counts = {
        split: row_count * ratio for split, ratio in SPLIT_RATIOS.items()
    }
    counts = {split: int(value) for split, value in exact_counts.items()}
    remaining = row_count - sum(counts.values())
    remainder_order = sorted(
        SPLIT_RATIOS,
        key=lambda split: exact_counts[split] - counts[split],
        reverse=True,
    )
    for split in remainder_order[:remaining]:
        counts[split] += 1
    return counts


def stratified_split(
    data: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Split each label independently, then shuffle each output reproducibly."""
    split_rows: dict[str, list[int]] = {
        split: [] for split in SPLIT_RATIOS
    }
    rng = random.Random(RANDOM_SEED)

    for label in sorted(EXPECTED_LABELS):
        indexes = data.index[data["label"] == label].tolist()
        rng.shuffle(indexes)
        counts = allocate_counts(len(indexes))

        start = 0
        for split, count in counts.items():
            split_rows[split].extend(indexes[start : start + count])
            start += count

    result = []
    for split in SPLIT_RATIOS:
        indexes = split_rows[split]
        rng.shuffle(indexes)
        result.append(data.loc[indexes].reset_index(drop=True))

    return result[0], result[1], result[2]


def distribution_table(
    data: pd.DataFrame, column: str, column_title: str
) -> str:
    counts = data[column].fillna("<missing>").astype(str).value_counts().sort_index()
    lines = [f"| {column_title} | Count |", "|---|---:|"]
    lines.extend(f"| {value} | {count} |" for value, count in counts.items())
    return "\n".join(lines)


def label_distribution_table(data: pd.DataFrame) -> str:
    counts = data["label"].value_counts().reindex(sorted(EXPECTED_LABELS), fill_value=0)
    lines = ["| Label | Count | Share |", "|---|---:|---:|"]
    for label, count in counts.items():
        share = count / len(data) * 100 if len(data) else 0
        lines.append(f"| {label} | {count} | {share:.2f}% |")
    return "\n".join(lines)


def build_report(
    original_rows: int,
    cleaned: pd.DataFrame,
    removed_empty: int,
    removed_duplicates: int,
    splits: dict[str, pd.DataFrame],
) -> str:
    split_counts = "\n".join(
        f"| {name} | {len(data)} |"
        for name, data in splits.items()
    )
    split_labels = "\n\n".join(
        f"### {name.title()}\n\n{label_distribution_table(data)}"
        for name, data in splits.items()
    )
    split_sources = "\n\n".join(
        f"### {name.title()}\n\n{distribution_table(data, 'source', 'Source')}"
        for name, data in splits.items()
    )

    return f"""# Message Dataset Preprocessing Report

Generated by `app/services/prepare_message_data.py`.

## Cleaning summary

- Original rows: {original_rows}
- Removed empty or invalid message records: {removed_empty}
- Removed duplicate messages: {removed_duplicates}
- Final cleaned rows: {len(cleaned)}
- Labels were stripped and normalized to lowercase. Valid labels: `smish`, `normal`, `promo`.
- All valid message text and source values were preserved; no translation or text normalization was applied to saved messages.
- Input used: `backend/bipod_erao_dataset.csv` only. No other dataset was read or combined.

## Cleaned label distribution

{label_distribution_table(cleaned)}

## Train, validation, and test sizes

| Split | Rows |
|---|---:|
{split_counts}

Requested proportions: 70% training, 15% validation, 15% testing. Integer allocations are stratified per label using largest remainders. Seed: `{RANDOM_SEED}`.

## Label distribution by split

{split_labels}

## Source/language distribution

The original `source` field is preserved. Its values describe the dataset's language/source categories; they are not inferred or changed during preprocessing.

### Cleaned dataset

{distribution_table(cleaned, 'source', 'Source')}

{split_sources}

## Duplicate leakage check

Duplicate detection uses a comparison key that trims/collapses whitespace and ignores letter case, while leaving the stored message text unchanged. Duplicate messages across train/validation/test: **0**. No duplicate-message key occurs in more than one split.

## Outputs

- `backend/dataset/processed/messages_clean.csv`
- `backend/dataset/processed/train.csv`
- `backend/dataset/processed/validation.csv`
- `backend/dataset/processed/test.csv`
- `backend/dataset/processed/preprocessing_report.md`
"""


def prepare_dataset() -> dict[str, object]:
    backend_dir = Path(__file__).resolve().parents[2]
    source_path = backend_dir / "bipod_erao_dataset.csv"
    output_dir = backend_dir / "dataset" / "processed"

    if not source_path.is_file():
        raise FileNotFoundError(f"Primary dataset not found: {source_path}")

    original = pd.read_csv(source_path, dtype=str, keep_default_na=False)
    expected_columns = {"label", "text", "source"}
    missing_columns = expected_columns - set(original.columns)
    if missing_columns:
        raise ValueError(
            "Primary dataset is missing required columns: "
            + ", ".join(sorted(missing_columns))
        )

    original_rows = len(original)
    data = original[["label", "text", "source"]].copy()

    labels = data["label"].str.strip().str.lower()
    invalid_labels = sorted(set(labels) - EXPECTED_LABELS)
    if invalid_labels:
        raise ValueError(
            "Unexpected or empty labels found: "
            + ", ".join(repr(label) for label in invalid_labels)
        )
    data["label"] = labels

    valid_message = data["text"].map(
        lambda value: isinstance(value, str) and bool(value.strip())
    )
    removed_empty = int((~valid_message).sum())
    data = data.loc[valid_message].copy()

    data["_message_key"] = data["text"].map(message_key)
    duplicate = data["_message_key"].duplicated(keep="first")
    removed_duplicates = int(duplicate.sum())
    data = data.loc[~duplicate].drop(columns="_message_key").reset_index(drop=True)

    if data.empty:
        raise ValueError("No valid message rows remain after cleaning.")
    if not set(data["label"]).issubset(EXPECTED_LABELS):
        raise ValueError("Cleaned data contains labels outside the expected set.")
    if any((data["label"] == label).sum() < 3 for label in EXPECTED_LABELS):
        raise ValueError("Each expected label needs at least 3 records to split.")

    train, validation, test = stratified_split(data)
    splits = {"train": train, "validation": validation, "test": test}

    split_keys = {
        name: set(frame["text"].map(message_key))
        for name, frame in splits.items()
    }
    if (
        split_keys["train"] & split_keys["validation"]
        or split_keys["train"] & split_keys["test"]
        or split_keys["validation"] & split_keys["test"]
    ):
        raise RuntimeError("Duplicate-message leakage found between splits.")
    if sum(map(len, splits.values())) != len(data):
        raise RuntimeError("Split row counts do not match the cleaned dataset.")

    output_dir.mkdir(parents=True, exist_ok=True)
    data.to_csv(output_dir / "messages_clean.csv", index=False, encoding="utf-8")
    for name, frame in splits.items():
        frame.to_csv(output_dir / f"{name}.csv", index=False, encoding="utf-8")

    report = build_report(
        original_rows,
        data,
        removed_empty,
        removed_duplicates,
        splits,
    )
    (output_dir / "preprocessing_report.md").write_text(
        report, encoding="utf-8"
    )

    return {
        "original_rows": original_rows,
        "cleaned_rows": len(data),
        "removed_empty": removed_empty,
        "removed_duplicates": removed_duplicates,
        "label_counts": data["label"].value_counts().to_dict(),
        "split_counts": {name: len(frame) for name, frame in splits.items()},
        "output_dir": output_dir,
    }


if __name__ == "__main__":
    summary = prepare_dataset()
    print(f"Original rows: {summary['original_rows']}")
    print(f"Final cleaned rows: {summary['cleaned_rows']}")
    print(f"Removed empty/invalid messages: {summary['removed_empty']}")
    print(f"Removed duplicate messages: {summary['removed_duplicates']}")
    print(f"Label counts: {summary['label_counts']}")
    print(f"Split counts: {summary['split_counts']}")
    print(f"Outputs written to: {summary['output_dir']}")
